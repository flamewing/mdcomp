"""Capture qualified external encodings from compare_external.py reports (offline)."""
import argparse
import hashlib
import json
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def render(fixtures):
    lines = ["// Generated by tests/support/capture_external_fixtures.py; review external.json.\n"]
    for f in fixtures:
        lines.append('{"%s", "%s", hex("%s"), hex("%s"), {"external-reference"}, {}, {}},\n'
                     % (f["id"], f["codec"], f["compressed_hex"], f["input_hex"]))
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--comparison-root", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="Check committed hashes and generated C++ without references")
    args = parser.parse_args()
    if args.check:
        fixtures = json.loads((args.output_dir / "external.json").read_text())["fixtures"]
        ids = set()
        for f in fixtures:
            if f["id"] in ids:
                parser.error("Duplicate fixture: " + f["id"])
            ids.add(f["id"])
            for field, hash_field in (("compressed_hex", "compressed_sha256"), ("input_hex", "input_sha256")):
                if digest(bytes.fromhex(f[field])) != f[hash_field]:
                    parser.error("Fixture hash mismatch: " + f["id"])
            original = bytes.fromhex(f["compressed_hex"])
            if f["reference"] == "snkrle":
                count = int.from_bytes(original[:2], "big")
                if count % 32:
                    parser.error("RLE fixture is not tile-aligned: " + f["id"])
                original = (count // 32).to_bytes(2, "big") + original[2:]
            if digest(original) != f["original_compressed_sha256"]:
                parser.error("Original encoding hash mismatch: " + f["id"])
        if (args.output_dir / "external.inc").read_text() != render(fixtures):
            parser.error("Generated C++ does not match external.json")
        print("Verified", len(fixtures), "external fixtures")
        return
    if args.comparison_root is None:
        parser.error("Capture requires --comparison-root")
    fixtures = []
    for reference in ("kens-rc3", "kenssharp", "snkrle", "accurate-kosinski",
                      "original-saxman", "clownlzss", "clownnemesis", "clownnemesis-accurate"):
        directory = args.comparison_root / (reference + "-comparison")
        report = json.loads((directory / "report.json").read_text())
        for row in report["cases"]:
            if not row["passed"]:
                continue
            if row["case"] not in ("zeros-32", "ascending-32", "run-257-then-literals",
                                    "run-258-then-literals", "final-pair", "final-run-257"):
                continue
            codec = {"KosinskiPlus": "kosplus"}.get(row["codec"], row["codec"].lower())
            case_dir = directory / row["codec"].lower() / row["case"]
            raw = (case_dir / "input.bin").read_bytes()
            original = (case_dir / "reference.compressed").read_bytes()
            compressed = original
            adaptation = "none"
            if reference == "snkrle":
                compressed = (int.from_bytes(original[:2], "big") * 32).to_bytes(2, "big") + original[2:]
                adaptation = "BE16 header converted from tiles to bytes; token body unchanged"
            fixtures.append({"id": reference + "-" + codec + "-" + row["case"],
                             "reference": reference, "codec": codec, "case": row["case"],
                             "qualification": "Both self-decodes and both cross-decodes match the deterministic input",
                             "header_adaptation": adaptation,
                             "original_compressed_sha256": digest(original),
                             "compressed_sha256": digest(compressed), "input_sha256": digest(raw),
                             "compressed_hex": compressed.hex(), "input_hex": raw.hex()})
    if not fixtures:
        parser.error("No qualified fixtures found")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    manifest = {"classification": "reference-generated; see ../references/external.json for pins, licenses and lineage",
                "fixtures": fixtures}
    (args.output_dir / "external.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (args.output_dir / "external.inc").write_text(render(fixtures))
    print("Captured", len(fixtures), "qualified encodings")


if __name__ == "__main__":
    main()
